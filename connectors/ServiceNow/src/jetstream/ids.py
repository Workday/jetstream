"""UUIDv7 generator.

Every id generated by a Jetstream connector must be a UUIDv7 so that ids
generated close together in time sort close together, which improves
partition pruning and file clustering in Iceberg.

Python 3.13+ ships `uuid.uuid7()`; on older runtimes we fall back to a
minimal RFC 9562 implementation.
"""
from __future__ import annotations

import os
import time
import uuid


def _uuid7_fallback() -> uuid.UUID:
    """RFC 9562 §5.7 — 48-bit unix_ts_ms + 4-bit ver + 12 bits rand_a
    + 2-bit var + 62 bits rand_b."""
    ts_ms = int(time.time() * 1000) & ((1 << 48) - 1)
    rand_a = int.from_bytes(os.urandom(2), "big") & 0x0FFF
    rand_b = int.from_bytes(os.urandom(8), "big") & ((1 << 62) - 1)
    val = (
        (ts_ms << 80)
        | (0x7 << 76)             # version 7
        | (rand_a << 64)
        | (0b10 << 62)            # RFC 4122 variant
        | rand_b
    )
    return uuid.UUID(int=val)


_native_uuid7 = getattr(uuid, "uuid7", None)


def uuid7() -> str:
    """Return a UUIDv7 as a canonical string."""
    if _native_uuid7 is not None:
        return str(_native_uuid7())
    return str(_uuid7_fallback())
